    <h1>Las cédulas del Jardín (<i>V. beta 1.0</i>)</h1>

    <div class="row justify-content-around py-5">
        <p>Las Cédulas del Jardín es una plataforma de código libre, gratuita, colaborativa y multilingüe,
            creada y mantenida por los Investigadores por México del Jardín Etnobiológico de Oaxaca.
            Se pone a disposición de comunidades, pueblos, jardines etnobiológicos o personas interesadas en <b>traducir</b> o en crear su propio
            <b>jardín virtual</b> y <b>documentar</b> en su propia lengua los saberes relacionados a su patrimonio biocultural.</p>

        <p>Busca ser un punto de encuentro en el que se pueda valorar, conocer, preservar y sobre todo reconocer los saberes locales
            en lenguas originarias o en español, en forma de breves artículos, cédulas, monografías, audios, imágenes o videos.
            Los materiales se organizan bajo el esquema de <b><a href="/jardiness" class="nolink" target="_new">jardines virtuales</a></b> que representan al colectivo de
            autores de un mismo lugar que genera los materiales.</p>

        <p>Si quieres participar, revisa nuestra <b><a href="/normaeditorial" class="nolink" target="_new">norma editorial</a></b>
            y el paso a paso de <b><a href="/comopublicar" class="nolink" target="_new">cómo publicar.</a></b><br>
            Si quieres revisar los materiales publicados, dirígete a la sección de <b><a href="/cedulasdeljardin" class="nolink">Las cédulas</a></b>.</p>

