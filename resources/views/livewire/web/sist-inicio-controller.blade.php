        <div class="col-sm-auto col-md-8 px-4 mb-4" style="text-align: justify;">

            <p>El patrimonio biocultural es el vínculo vivo e inextricable entre la diversidad biológica y la
                diversidad cultural, que se genera, protege y hereda por los pueblos, en un territorio y un tiempo
                específicos.</p>

            <p>No se limita sólo a especies, ecosistemas, recursos naturales, usos o artefactos materiales; abarca
                saberes, prácticas, lenguas, rituales, sistemas productivos, toponimias y cosmovisiones que los
                pueblos han desarrollado mediante la interacción continua con las plantas, hongos,
                microorganismos y animales de su entorno.</p>

            <p>Este patrimonio, es la herencia o legado territorializado de los pueblos, le pertenece a los
                pueblos que lo poseen y transmiten, es de propiedad colectiva y se hereda y adapta generación
                tras generación mediante su socialización y/o enseñanza.</p>
            </div>

        <div class="row justify-content-around"  style="text-align: justify;">
            <p>A diferencia de los inventarios tradicionales, la documentación biocultural se debe construir bajo protocolos éticos que
                salvaguarden la propiedad intelectual colectiva, respetan los conocimientos sagrados o restringidos, y garanticen el derecho
                de las comunidades a decidir qué, cómo y para qué se documenta o que no se documenta. </p>
            <p>El portal de “Las Cédulas del Jardín” adopta el <b><a href="https://revistaetnobiologia.mx/index.php/etno/article/view/338" class="nolink" target="otro">Código de Ética para la investigación, la
                investigación-acción y la colaboración etnocientífica en América Latina</a></b>, aprobado por la
                Asamblea General de la Sociedad Latinoamericana de Etnobiología en octubre de 2016 en
                Popayán, Colombia. El cual tiene como objetivo principal transformar la relación extractivista
                entre investigadores y comunidades, estableciendo una colaboración basada en el respeto, la
                reciprocidad y la justicia social.</p>

            <p>La <b><a href="https://www.diputados.gob.mx/LeyesBiblio/pdf/LGMHCTI.pdf" class="nolink" target="_blank">Ley General
                en Materia de Humanidades, Ciencias, Tecnologías e Innovación</a></b> de México, en su artículo 53 establece: &quot;la constitución y consolidación de una
                Red Nacional de Jardines Etnobiológicos que tendrá por objeto conservar la riqueza biocultural y promover el cuidado de
                los territorios y bienes comunes.  .... procurará que en cada entidad federativa se cuente al menos con uno de estos espacios.&quot;</p>

            <p>Los Jardines Etnobiológicos tienen que visibilizar, resguardar, difundir y sobre todo, acompañar, reconocer y dar lugar
                a los autores y poseedores del conocimiento sobre la naturaleza que tienen los pueblos originarios y que
                conforma la riqueza biocultural de los pueblos de México, incluyendo las lenguas en la que son generados.  La
                participación de los Jardines Etnobiológicos en la sistematización de información y en el impulso y acompañamiento de los procesos de
                auto documentación por parte de las propias comunidades debe ser prioritario.</p>
        </div>

