            <h3>Características del sistema</h3>
            <ul>
            <li><b>Multilingüe</b>. Además de ser un punto de encuentro para la traducción de materiales, cuenta con la capacidad de interactuar con
                los traductores a distancia para traducir el contenido de cada una de las cédulas.
                Cuenta con teclado de caracteres especiales para representar correctamente la escritura de las diferentes lenguas.</li>

            <li><b>Libre</b>. Al estar bajo la licencia GNU GPL, el sistema consituye software libre, por lo que se permite su adopción o mejora por
                parte de cualquier comunidad.</li>

            <li><b>Con compromiso Ético</b>. El sistema se alinea al <b><a href="https://revistaetnobiologia.mx/index.php/etno/article/view/338" class="nolink" target="otro">Código de Ética para la
                investigación, la investigación-acción y la colaboración etnocientífica en América Latina</a></b>, aprobado por la
                Asamblea General de la Sociedad Latinoamericana de Etnobiología en octubre de 2016 en Popayán, Colombia.</li>

            <li><b>Accesible</b>. Al ser un sistema basado en la web, permite el acceso a las cédulas desde cualquier dispositivo con conexión a internet,
                facilitando su consulta y difusión tanto en los jardines como en las comunidades o desde cualquier parte del mundo.</li>

            <li><b>Aportaciones públicas</b>. Incluye un módulo mediante el cual los visitantes pueden enviar sus aportaciones al conocimiento
                sobre cada una de las publicaciones, la cual se muestra al público luego de pasar por un proceso de revisión.</li>

            <li><b>Respeta la oralidad</b>. Permite asociar archivos de audio  para preservar
                la tradición oral, así como para facilitar la traducción e inclusión de lenguas carentes o de compleja escritura.</li>

            <li><b>Evita el extractivismo</b>. Reconoce y nombra a cada uno de los pueblos o cumunidades como las propietarias,
                preservadoras y garantes del conocimiento.</li>

            <li><b>Es colaborativo</b>. Cuenta con diversos roles que facilitan la interacción a distancia para la creación, traducción,
                revisión editorial y publicación de los materiales. </li>

            <li><b>Interactivo</b>. Incluye funcionalidades para agregar información en formato de texto, audio, imágen o video.</li>

            <li><b>Catalogable</b>. Genera una dirección URL única y fija para cada una de las cédulas de documentacion a las cuales se puede
                acceder desde una navegador de internet o mediante el escaneo de un código QR (generado por el sistema),
                o mediante la <b>asignación de un numero DOI</b>.</li>

            <li><b>Incorpora redes sociales</b>. Permite incorporar referencias a canales, publicaciones y videos de documentación externa
                generadas por el público en diversas redes sociales.</li>

            <li><b>Jardines virtuales</b>. Permite registrar uno o más jardines virtuales en un mismo sistema, manteniendo la independencia en la asignación de roles y
                administración de contenidos, ahorrando recursos de infraestructura y respetando el origen de los saberes.
                Al consultar un material, el sistema avisa al visitante de la existencia de materiales similares en otros jardines virtuales.</li>

            <li><b>Seguro</b>. Cuenta con un robusto sistema de seguridad que permite generar cuentas asociadas a un correo electrónico
                y asignarles roles específicos, promoviendo la colaboración comunitaria, al permitir que hablantes nativos, lingüistas y educadores
                contribuyan a la creación, edición o traducción de contenido desde sus comunidades mediante el
                acceso a la plataforma por internet.</li>

            <li><b>Catálogos homologados</b>. Con el objeto de homologar la información, incorpora catálogos especializados, como algunos de
                ubicación del <b><a href="https://www.inegi.org.mx/"  class="nolink" target="new">INEGI</a></b>, de
                <b><a href="https://www.ethnologue.com/" class="nolink" target="new">lenguas del ethnologue</a></b> o de especies botánicas
                <b><a href="https://powo.science.kew.org/" class="nolink" target="new"> Plants of the World</a></b> de Kew</li>

            <li><b>API</b>. Cuenta con protocolo de comunicación http cifrado, lo que permite recibir peticiones y enviar información sobre las publicaciones, jardines virtuales,
                autores y traductores, para su integración con otros sistemas de información <i>(En construcción)</i>.</li>
